export const popularPlaceIds = new Set(popularPlaces.map(p => p.name.en.toLowerCase()));
export const popularPlaceIdsBn = new Set(popularPlaces.map(p => p.name.bn.toLowerCase()));

export function getPopularTier(placeName) {
  const normalized = (placeName || '').toLowerCase().trim();
  for (const p of popularPlaces) {
    if (p.name.en.toLowerCase() === normalized || p.name.bn.toLowerCase() === normalized) {
      return p.tier;
    }
  }
  return null;
}

export function findPopularPlace(placeName) {
  const normalized = (placeName || '').toLowerCase().trim();
  return popularPlaces.find(p =>
    p.name.en.toLowerCase() === normalized || p.name.bn.toLowerCase() === normalized
  ) || null;
}
